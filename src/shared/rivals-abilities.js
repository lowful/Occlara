'use strict';

/**
 * The Rivals ability gate: never tell a player to press a button they do not have.
 *
 * The Valorant coach has had this guard since early on (validateTipForAgent in
 * coaching-engine.js) and Rivals has had nothing, because nothing here knew
 * which hero the player was on. That changed: hero select PRINTS the hero name
 * in large type, and the model reads printed text correctly. Graded on a real
 * Season 10 frame it returned "the punisher" exactly, twice, on the same day it
 * scored 17 to 42% precision naming heroes from scoreboard portraits. Text is
 * not art, and this gate is the first thing that read difference pays for.
 *
 * IT WORKS BY NEGATIVE SPACE, the same as the Valorant one. It does not try to
 * decide whether a tip is good. It asks one question with a checkable answer:
 * does this sentence name an ability, and is that ability one the player can
 * actually use. Everything it does not know about, it permits.
 *
 * THREE THINGS IT DELIBERATELY ALLOWS:
 *
 * 1. An unknown hero permits everything. Absence means silence everywhere else
 *    in this codebase; here silence means no opinion, not rejection. A gate that
 *    fired while the hero was unknown would block every tip in a match where
 *    hero select was never captured, which is most of them.
 * 2. An ability whose OWNER is named in the same sentence. "The Thing has Yancy
 *    Street Charge, which leaves a zone that turns your dash off" is the single
 *    most valuable sentence the counter table produces, and a naive gate eats it
 *    because Yancy Street Charge belongs to somebody else. Naming the owner is
 *    what separates describing an enemy's tool from ordering you to press it.
 * 3. Ordinary English that happens to be an ability name. Cloak & Dagger have
 *    abilities literally called Cloak and Dagger, and "break line of sight and
 *    cloak out" is a sentence any coach might write about any hero. See GENERIC.
 *
 * The data is generated by npm run sync:rivals from the game's own hero pages,
 * into rivals-abilities.generated.json beside this file. It is a SECOND, smaller
 * copy of server/rivals-data.generated.json and that is deliberate: package.json
 * ships src/ and does not ship server/, so a require reaching across would work
 * in the repo and throw MODULE_NOT_FOUND on a real install.
 */

let DATA = {};
try {
  DATA = require('./rivals-abilities.generated.json').abilities || {};
} catch {
  // A missing file costs the gate, not the coach. Every function below treats
  // an empty table as "nothing is checkable", which permits everything, which
  // is the same answer an unknown hero gets.
  DATA = {};
}

/**
 * Lowercase, collapse whitespace, and FOLD DIACRITICS.
 *
 * The folding is not decoration. Exactly one ability in the game carries a
 * diacritic, Gorr's Ragnarök, and the odds that a tip spells it with the umlaut
 * are poor: the model writes what it writes, and "Pop Ragnarok when they group"
 * is the sentence a coach actually produces. Without folding, that tip sails
 * through the gate while the identically meant "Ragnarök" is caught, which is
 * the worst kind of guard, one that works only on the input you tested it with.
 */
const norm = (s) => String(s || '')
  .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .toLowerCase().replace(/\s+/g, ' ').trim();

/**
 * Ability names that are also ordinary words, and must never be matched.
 *
 * check-playbook.js carries a list like this for the Valorant side and its
 * comment records why: a substring test flagged the word "cover" as Harbor's
 * Cove. These three are the Rivals equivalent, found by listing every
 * single-word ability name in the generated data and asking which could appear
 * in a coaching sentence meaning something else:
 *
 *   cloak     "break line of sight and cloak out" is generic coaching English
 *   dagger    same, and Cloak & Dagger own both halves anyway
 *   backstab  a thing any flanker does, not only the hero whose ability it is
 *
 * The other eighteen single-word names are Ragnarök, Soulsword, Unibeam,
 * Thorforce, Telekinesis, Darkchild, Doppelganger, Heartbreaker, Roterstern,
 * Supernova, Deception, Deliverance, Adjudication, B.R.B., C.Y.A., Objection!
 * and Upgrade!, none of which a coach writes by accident.
 */
const GENERIC = new Set(['cloak', 'dagger', 'backstab']);

/**
 * Is this ability name specific enough to match on?
 *
 * A short generic token produces false rejections, which are worse than misses:
 * a missed ability name costs one bad tip, a false rejection silences a good
 * one and looks like the coach has nothing to say.
 */
function checkable(name) {
  const n = norm(name);
  if (!n || GENERIC.has(n)) return false;
  return /[ \-/.]/.test(n) || n.length >= 6;
}

/** Every hero who has an ability by this name, lowercased. Team-ups have two. */
function ownersOf(ability) {
  const a = norm(ability);
  const out = [];
  for (const hero of Object.keys(DATA)) {
    if ((DATA[hero] || []).some((x) => norm(x) === a)) out.push(hero);
  }
  return out;
}

/** The ability names a hero can actually use, normalised. Empty for an unknown hero. */
function abilitiesOf(hero) {
  const want = norm(hero);
  for (const name of Object.keys(DATA)) {
    if (norm(name) === want) return (DATA[name] || []).map(norm);
  }
  return [];
}

/**
 * Does this tip order the player to use an ability their hero does not have?
 *
 * @param {string} tip    the sentence about to reach the player
 * @param {string} hero   the hero the player is on, or null if not read yet
 * @returns {{ok: boolean, why?: string, ability?: string, owner?: string}}
 */
function validateTipForHero(tip, hero) {
  const text = norm(tip);
  if (!text) return { ok: true };

  const own = abilitiesOf(hero);
  // An unknown hero, or one the sync has never seen, means no opinion.
  if (!own.length) return { ok: true };
  const owned = new Set(own);

  for (const [ownerName, list] of Object.entries(DATA)) {
    if (norm(ownerName) === norm(hero)) continue;
    for (const ability of list || []) {
      const a = norm(ability);
      if (!checkable(a) || owned.has(a)) continue;
      if (!text.includes(a)) continue;
      // Named its owner, so it is describing an enemy's tool rather than
      // ordering the player to press it. This is the counter table's whole
      // sentence shape and it must survive.
      //
      // CONTINUE, not return. Excusing one attributed ability must not stop the
      // scan: "The Thing has Yancy Street Charge, so use Web-Swing out" names an
      // owner AND then orders a Web-Swing the player may not have, and an early
      // return would pass the whole sentence on the strength of the first half.
      if (text.includes(norm(ownerName))) continue;
      return { ok: false, why: 'ability the player does not have',
        ability, owner: ownerName };
    }
  }
  return { ok: true };
}

module.exports = { validateTipForHero, abilitiesOf, ownersOf, checkable, GENERIC };
